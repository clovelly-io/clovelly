#!/usr/bin/env bash
# Regenerates the protobuf and gRPC modules in src/clovelly/ from the repository's proto/.
# Run from anywhere, with a Python that has the pinned grpcio-tools (`pip install -e '.[dev]'`).
#
# The generated packages (clovelly.cell.v1, clovelly.control.v1, clovelly.verifier.v1) land inside our own `clovelly`
# package because the proto packages are named clovelly.*. grpc.health.v1 is not generated:
# a generated grpc/ package would shadow the grpc library, so the SDK uses
# grpcio-health-checking's grpc_health.v1 instead (the same wire protocol).
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
proto="$here/../../proto"
out="$here/src"
python="${PYTHON:-python}"

"$python" - <<'EOF'
import sys
try:
    import grpc_tools
except ImportError:
    sys.exit("gen.sh: grpcio-tools is missing; run `pip install -e '.[dev]'` first")
EOF

"$python" -m grpc_tools.protoc \
  -I "$proto" \
  --python_out="$out" \
  --pyi_out="$out" \
  --grpc_python_out="$out" \
  clovelly/cell/v1/cell.proto \
  clovelly/verifier/v1/verifier.proto \
  clovelly/control/v1/control.proto

for pkg in clovelly/cell clovelly/cell/v1 clovelly/control clovelly/control/v1 clovelly/verifier clovelly/verifier/v1; do
  init="$out/$pkg/__init__.py"
  [ -f "$init" ] || printf '# Generated by gen.sh from proto/%s.\n' "$pkg" > "$init"
done

echo "gen.sh: wrote $out/clovelly/{cell,control,verifier}/v1"
